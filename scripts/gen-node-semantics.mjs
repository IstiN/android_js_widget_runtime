#!/usr/bin/env node
// Generate docs/node-semantics.md from the pinned contract node pages and the
// mapper registry status (docs/node-support.json). Run from the repository
// root after `scripts/fetch-conformance.sh`:
//   node scripts/gen-node-semantics.mjs
// The Android column mirrors the mapper registry in NodeMappers.kt: when a
// mapper changes, update ANDROID below and regenerate.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const nodesDir = '.conformance/js_widget_runtime/docs/contract/nodes';
const supportFile = 'docs/node-support.json';
const outFile = 'docs/node-semantics.md';

// type -> [android view, applied prop names] (mirror of NodeMappers.kt).
const ANDROID = {
  center: ['FrameLayout (child centered)', []],
  column: ['LinearLayout vertical', ['spacing']],
  row: ['LinearLayout horizontal', ['spacing']],
  stack: ['FrameLayout z-order', []],
  padding: ['FrameLayout with padding', ['padding']],
  sizedBox: ['FrameLayout fixed size', ['width', 'height']],
  spacer: ['View (empty space)', ['flex (ignored)']],
  absoluteFill: ['FrameLayout fill', ['color']],
  fill: ['FrameLayout fill', ['color']],
  container: ['LinearLayout + background', ['decoration.color', 'borderRadius', 'padding']],
  card: ['LinearLayout + rounded background', ['decoration.color or color', 'padding']],
  text: ['TextView', ['data', 'text', 'label', 'fontSize', 'color', 'fontWeight']],
  textField: ['EditText', ['hint', 'initialValue']],
  textArea: ['EditText multi-line', ['hint', 'initialValue']],
  badge: ['FrameLayout + label overlay', ['label', 'data', 'text', 'backgroundColor']],
  chip: ['TextView rounded', ['label', 'data', 'text', 'onTap']],
  divider: ['View line', ['thickness', 'color']],
  circularProgressIndicator: ['ProgressBar indeterminate', []],
  linearProgressIndicator: ['ProgressBar horizontal', ['value (0..1 to 0..100)']],
  button: ['Button', ['data', 'text', 'label', 'onTap', 'onPressed', 'onPress', 'payload']],
  textButton: ['Button', ['data', 'text', 'label', 'onTap', 'onPressed', 'onPress', 'payload']],
  outlinedButton: ['Button', ['data', 'text', 'label', 'onTap', 'onPressed', 'onPress', 'payload']],
  fab: ['Button with round background', ['label', 'data', 'text', 'onTap', 'onPressed', 'onPress', 'payload']],
  checkbox: ['CheckBox', ['value', 'label', 'data', 'text']],
  switch: ['Switch', ['value']],
  slider: ['SeekBar 0..100', ['value', 'min', 'max']],
  dropdown: ['Spinner', ['items', 'options', 'value']],
  radio: ['RadioButton', ['value', 'groupValue', 'label', 'data', 'text']],
  gestureDetector: ['clickable FrameLayout', ['onTap', 'onPressed', 'onPress', 'payload']],
  inkWell: ['clickable FrameLayout', ['onTap', 'onPressed', 'onPress', 'payload']],
  scroll: ['ScrollView vertical column', []],
  listView: ['ScrollView vertical column (no view recycling)', []],
  listTile: ['LinearLayout title + subtitle', ['title', 'data', 'label', 'subtitle', 'onTap', 'onPress']],
  appBar: ['LinearLayout bar + title text', ['title', 'color']],
  banner: ['LinearLayout + message text', ['message', 'backgroundColor']],
  opacity: ['View alpha', ['opacity']],
  rect: ['View rounded rectangle', ['width', 'height', 'radius', 'fill']],
  circle: ['View circle', ['size', 'fill']],
};

const support = JSON.parse(readFileSync(supportFile, 'utf8'));
const supportByType = Object.fromEntries(support.map((r) => [r.type, r]));

function pageProps(type) {
  const text = readFileSync(join(nodesDir, `${type}.md`), 'utf8');
  const category = (text.match(/^Category: \*\*(.+)\*\*/m) || [])[1] || 'unknown';
  const props = [];
  const table = text.match(/^## Props\n\n((?:\|.*\n)+)/m);
  if (table) {
    const rows = table[1].trim().split('\n');
    for (const line of rows.slice(2)) { // skip header and separator
      const cells = line.split('|').map((s) => s.trim().replaceAll('`', ''));
      const [name, type_, def, effect] = [cells[1], cells[2], cells[3], cells[4]];
      props.push({ name, type: type_, def, effect });
    }
  }
  return { category, props };
}

function androidBehavior(type) {
  const mapped = ANDROID[type];
  if (mapped) return { view: mapped[0], applied: mapped[1] };
  if (supportByType[type]?.reason === 'host contract') {
    return { view: 'HostContractView container + slot (host fills it)', applied: [] };
  }
  return { view: 'fallback card [type] with the node id tag', applied: [] };
}

const lines = [];
lines.push('# Node semantics: Flutter versus Android');
lines.push('');
lines.push('One table per registered node type (plan 6.1 A3, issue #4). Flutter behavior');
lines.push('comes from the pinned contract node pages');
lines.push('(`.conformance/js_widget_runtime/docs/contract/nodes`), the Android column');
lines.push('mirrors the mapper registry (`NodeMappers.kt`). Generated by');
lines.push('`scripts/gen-node-semantics.mjs`; regenerate after mapper changes.');
lines.push('');
lines.push('Support status: `yes` = mapped to a real view; `partial` (host contract) =');
lines.push('a host surface fills the slot; `partial` (fallback) = reference fallback card.');
lines.push('');

for (const row of support) {
  const type = row.type;
  const { category, props } = pageProps(type);
  const android = androidBehavior(type);
  lines.push(`## \`${type}\``);
  lines.push('');
  lines.push(`- Category: ${category}`);
  lines.push(`- Android status: **${row.status}**${row.reason ? ` (${row.reason})` : ''}`);
  lines.push(`- Android view: ${android.view}`);
  lines.push('');
  if (props.length === 0) {
    lines.push('No documented props.');
    lines.push('');
    continue;
  }
  lines.push('| Prop | Flutter | Android | Difference |');
  lines.push('|---|---|---|---|');
  for (const p of props) {
    const applied = android.applied.some((a) => p.name === a || a.startsWith(p.name));
    const flutter = `\`${p.type}\`, default ${p.def === '—' ? '—' : `\`${p.def}\``}`;
    const androidCol = applied ? `applied (${android.view})` : 'not applied';
    const diff = applied ? '' : 'rendering differs';
    lines.push(`| \`${p.name}\` | ${flutter} | ${androidCol} | ${diff} |`);
  }
  lines.push('');
}

writeFileSync(outFile, lines.join('\n'));
console.log(`wrote ${outFile}: ${support.length} node sections`);
